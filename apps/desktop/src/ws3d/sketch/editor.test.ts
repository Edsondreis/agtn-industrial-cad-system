import { pointOf, profiles } from "@agtn/sketch";
import { SketchEditor } from "./editor";
import { emptySketch } from "@agtn/sketch";

const near = (a: number, b: number) => expect(Math.abs(a - b)).toBeLessThan(1e-6);

describe("editor de esboço", () => {
  it("retângulo da origem + 2 cotas = totalmente definido; mudar a cota ajusta", () => {
    const ed = new SketchEditor(emptySketch());
    ed.setTool("rect");
    ed.click({ p: { x: 0, y: 0 }, point: "O" });
    ed.click({ p: { x: 180, y: 90 } });
    expect(ed.getState().solve.status).toBe("under");
    const lines = Object.values(ed.sketch.entities).filter((e) => e.t === "line");
    ed.setTool("dimension");
    ed.click({ p: { x: 90, y: 0 }, entity: lines[0].id });
    expect(ed.getState().prompt?.kind).toBe("length");
    near(ed.getState().prompt!.value, 180);
    expect(ed.confirmDimension(200)).toBe(true);
    ed.click({ p: { x: 200, y: 45 }, entity: lines[1].id });
    expect(ed.confirmDimension(100)).toBe(true);
    const st = ed.getState();
    expect(st.solve.status).toBe("full");
    const dim = st.sketch.constraints.find((c) => c.t === "length" && "v" in c && c.v === 200)!;
    ed.editDimension(dim.id);
    expect(ed.confirmDimension(350)).toBe(true);
    const far = Object.values(ed.sketch.points).map((p) => p.x);
    near(Math.max(...far), 350);
    near(profiles(ed.sketch).regions[0].area, 35000);
  });
  it("linha encadeada fecha no ponto inicial e ganha horizontal/vertical automáticas", () => {
    const ed = new SketchEditor(emptySketch());
    ed.setTool("line");
    ed.click({ p: { x: 0, y: 0 } });
    ed.click({ p: { x: 100, y: 0.5 } });
    const p1 = Object.keys(ed.sketch.points)[0];
    ed.click({ p: { x: 100, y: 60 } });
    ed.click({ p: { x: 0, y: 0 }, point: p1 });
    const kinds = ed.sketch.constraints.map((c) => c.t).sort();
    expect(kinds).toEqual(["horizontal", "vertical"]);
    expect(profiles(ed.sketch).regions.length).toBe(1);
    expect(ed.getState().clicks.length).toBe(0);
  });
  it("cota conflitante é recusada com mensagem e o esboço fica como estava", () => {
    const ed = new SketchEditor(emptySketch());
    ed.setTool("rect");
    ed.click({ p: { x: 0, y: 0 }, point: "O" });
    ed.click({ p: { x: 50, y: 50 } });
    const ls = Object.values(ed.sketch.entities);
    ed.setTool("dimension");
    ed.click({ p: { x: 25, y: 0 }, entity: ls[0].id });
    ed.confirmDimension(50);
    ed.click({ p: { x: 25, y: 50 }, entity: ls[2].id }); // lado oposto: já é igual (paralelo e conectado) → redundante ok? conflitante com 80
    const before = ed.sketch;
    expect(ed.confirmDimension(80)).toBe(false);
    expect(ed.getState().error).toMatch(/inconsistentes/i);
    expect(ed.sketch).toBe(before);
  });
  it("restrições pela seleção: paralelas, tangente, concêntricos; excluir e desfazer", () => {
    const ed = new SketchEditor(emptySketch());
    ed.setTool("line");
    ed.click({ p: { x: 0, y: 0 } });
    ed.click({ p: { x: 50, y: 10 } });
    ed.escape();
    ed.click({ p: { x: 0, y: 30 } });
    ed.click({ p: { x: 40, y: 45 } });
    ed.escape();
    const [a, b] = Object.values(ed.sketch.entities).map((e) => e.id);
    ed.setTool("select");
    ed.click({ p: { x: 0, y: 0 }, entity: a });
    ed.click({ p: { x: 0, y: 0 }, entity: b }, true);
    expect(ed.applicable()).toContain("parallel");
    ed.constrain("parallel");
    const P = (id: string) => pointOf(ed.sketch, id)!;
    const la = ed.sketch.entities[a] as { p1: string; p2: string };
    const lb = ed.sketch.entities[b] as { p1: string; p2: string };
    const cross = (P(la.p2).x - P(la.p1).x) * (P(lb.p2).y - P(lb.p1).y) - (P(la.p2).y - P(la.p1).y) * (P(lb.p2).x - P(lb.p1).x);
    near(cross, 0);
    ed.setTool("circle");
    ed.click({ p: { x: 100, y: 0 } });
    ed.click({ p: { x: 110, y: 0 } });
    ed.click({ p: { x: 103, y: 1 } });
    ed.click({ p: { x: 108, y: 1 } });
    const circles = Object.values(ed.sketch.entities).filter((e) => e.t === "circle").map((e) => e.id);
    ed.setTool("select");
    ed.click({ p: { x: 0, y: 0 }, entity: circles[0] });
    ed.click({ p: { x: 0, y: 0 }, entity: circles[1] }, true);
    ed.constrain("concentric");
    const cs = circles.map((id) => ed.sketch.entities[id] as { c: string });
    near(P(cs[0].c).x, P(cs[1].c).x);
    const n = Object.keys(ed.sketch.entities).length;
    ed.click({ p: { x: 0, y: 0 }, entity: circles[0] });
    ed.deleteSelection();
    expect(Object.keys(ed.sketch.entities).length).toBe(n - 1);
    expect(ed.sketch.constraints.some((c) => c.t === "concentric")).toBe(false);
    ed.undo();
    expect(Object.keys(ed.sketch.entities).length).toBe(n);
  });
  it("aparar pelo editor e arco por 3 pontos", () => {
    const ed = new SketchEditor(emptySketch());
    ed.setTool("line");
    ed.click({ p: { x: 0, y: 0 } });
    ed.click({ p: { x: 100, y: 0 } });
    ed.escape();
    ed.click({ p: { x: 50, y: -10 } });
    ed.click({ p: { x: 50, y: 10 } });
    ed.escape();
    const h = Object.values(ed.sketch.entities)[0].id;
    ed.setTool("trim");
    ed.click({ p: { x: 80, y: 0 }, entity: h });
    expect(ed.getState().error).toBeNull();
    const xs = Object.values(ed.sketch.points).map((p) => p.x);
    expect(Math.max(...xs)).toBeLessThan(100);
    ed.setTool("arc");
    ed.click({ p: { x: 0, y: 50 } });
    ed.click({ p: { x: 40, y: 50 } });
    ed.click({ p: { x: 20, y: 70 } });
    expect(Object.values(ed.sketch.entities).some((e) => e.t === "arc")).toBe(true);
  });
  it("arrastar ponto respeita as restrições (linha horizontal continua horizontal)", () => {
    const ed = new SketchEditor(emptySketch());
    ed.setTool("line");
    ed.click({ p: { x: 0, y: 0 } });
    ed.click({ p: { x: 100, y: 0 } });
    ed.escape();
    const l = Object.values(ed.sketch.entities)[0] as { p1: string; p2: string };
    expect(ed.beginDrag(l.p2)).toBe(true);
    ed.dragTo(l.p2, { x: 150, y: 40 });
    ed.endDrag();
    near(pointOf(ed.sketch, l.p2)!.y, pointOf(ed.sketch, l.p1)!.y);
    ed.undo();
    near(pointOf(ed.sketch, l.p2)!.x, 100);
  });
});
